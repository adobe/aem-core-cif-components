package com.adobe.cq.commerce.core.components.internal.servlets;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(name = "CIF Catalog Page Not Found Filter")
public @interface CatalogPageNotFoundFilterConfiguration {

    @AttributeDefinition(
        name = "Service unavailable on backend error",
        description = "Enabled by default: return HTTP 503 for catalog transport failures only in disabled WCM mode. "
            + "Set to false to restore the previous filter behavior (404 for failed entity lookups or an empty 200 category page), "
            + "without eagerly fetching category product searches in the filter. Author Edit/Preview and GraphQL-only errors are unchanged.")
    boolean serviceUnavailableOnBackendError() default true;

    @AttributeDefinition(
        name = "Retry after seconds",
        description = "A positive value sends a Retry-After header in seconds only on HTTP 503 responses generated by this filter. "
            + "The default is 0; zero or negative values omit the header. No header is added when backend error handling is disabled.")
    int retryAfterSeconds() default 0;
}
